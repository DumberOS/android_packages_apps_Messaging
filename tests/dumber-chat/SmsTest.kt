package com.android.messaging.dumber
import chat.dumber.sdk.*

fun main() {
    val now = 1_000_000L
    val r = SmsRequest("event", "12345678-1234-1234-1234-123456789012", "send", "+15555550101", "hello", now, now)
    check(ChatSmsPolicy.initial(r,now)=="unknown")
    check(ChatSmsPolicy.fresh(r,now+599_999))
    check(!ChatSmsPolicy.fresh(r,now+600_000))
    check(!ChatSmsPolicy.fresh(r.copy(createdAtMs=now-600_000),now))
    check(!ChatSmsPolicy.fresh(r.copy(receivedAtMs=now-600_000),now))
    check(!ChatSmsPolicy.fresh(r.copy(createdAtMs=now+30_001),now))
    check(!ChatSmsPolicy.fresh(r.copy(receivedAtMs=now+30_001),now))
    check(ChatSmsPolicy.initial(r.copy(body=""),now)=="failed")
    check(ChatSmsPolicy.initial(r.copy(body="x".repeat(1601)),now)=="failed")
    check(ChatSmsPolicy.initial(r.copy(address="123"),now)=="failed")
    check(ChatSmsPolicy.initial(r,now+600_000)=="expired")
    val sim = Sim(3,42,"Personal","+15555550102")
    val account = ChatAccount(Session("credentials","account","device",null),"+15555550102",3,42,null,"Personal","store","password",0)
    val id = ChatSmsPolicy.simId(sim,account)
    val v2 = r.copy(kind="send_v2",simId=id,transport="encrypted")
    check(ChatSmsPolicy.valid(v2))
    check(ChatSmsPolicy.matchesRoute(v2,id,"encrypted"))
    check(!ChatSmsPolicy.matchesRoute(v2,id,"sms"))
    check(!ChatSmsPolicy.matchesRoute(v2,id,"unknown"))
    check(!ChatSmsPolicy.matchesRoute(v2,ChatSmsPolicy.simId(sim.copy(cardId=43),account),"encrypted"))
    check(!ChatSmsPolicy.matchesRoute(v2,ChatSmsPolicy.simId(sim,account.copy(session=account.session.copy(credentials="replacement"))),"encrypted"))
    check(!ChatSmsPolicy.matchesRoute(v2,ChatSmsPolicy.simId(sim,null),"encrypted"))
    check(ChatSmsPolicy.transport(false,null)=="sms")
    check(ChatSmsPolicy.transport(true,null)=="unknown")
    check(ChatSmsPolicy.transport(true,Availability.AVAILABLE)=="encrypted")
    check(ChatSmsPolicy.transport(true,Availability.UNAVAILABLE)=="sms")
    check(ChatSmsPolicy.valid(v2.copy(body="x".repeat(10000))))
    check(!ChatSmsPolicy.valid(v2.copy(transport="sms",body="x".repeat(1601))))
    check(!ChatSmsPolicy.valid(v2.copy(simId="")))
    check(!ChatSmsPolicy.fresh(v2,now+600_000))
    val snapshot = SmsSnapshot("account","session",1,listOf("browser-one"))
    val first = snapshot.progress(0,20,250)
    check(first.offset == 0L && first.total == 250L && !first.complete)
    val resumed = snapshot.copy(count=200).progress(0,20,50)
    check(resumed.offset == 200L && resumed.total == 250L && !resumed.complete)
    val last = snapshot.copy(count=200).progress(40,10,50)
    check(last.offset == 240L && last.total == 250L && last.complete)
    check(snapshot.progress(0,0,0).complete)
    check(snapshot.copy(count=250,finished=true).progress(0,1,1).total == 251L)
    println("PASS: snapshot progress across bounded sync turns, resume, empty history and later updates")
    println("PASS: 15 SIM identity, replacement, route pinning and encrypted payload checks")
    println("PASS: 11 SMS expiry, future-clock and payload checks")
}
